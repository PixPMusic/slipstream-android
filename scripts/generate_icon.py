#!/usr/bin/env python3
"""Generate launcher artwork: python3 scripts/generate_icon.py (standard library only)."""

from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
BACKGROUND = "#0A2E42"
FOREGROUND = "#7DF0FA"

# Original Core Graphics coordinates from slipstream-swift/scripts/generate-icon.swift.
# Keep the curves and 38-unit round strokes; only scale and center for Android.
paths = []
for row in range(3):
    y = 350 + row * 132
    paths.append(
        f"M260,{y} C360,{y + 90} 412,{y - 90} 512,{y} "
        f"C612,{y + 90} 664,{y - 90} 764,{y}"
    )
path = " ".join(paths)

# Adaptive layers are 108 dp, with a central 72 dp visible area.
# Match the approved preview: ink spans 70% of that area, preserving proportions.
# The original glyph's width (including strokes) is 764 - 260 + 38 = 542.
scale = 72 * 0.7 / 542
translate_x = 54 - 512 * scale
# Core Graphics uses upward Y; Android and SVG use downward Y.
translate_y = 54 + 482 * scale


def write(relative_path: str, content: str) -> None:
    destination = ROOT / relative_path
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(content, encoding="utf-8")


write("app/src/main/res/drawable/ic_launcher_foreground.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_icon.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:scaleX="{scale:.12f}" android:scaleY="{-scale:.12f}"
        android:translateX="{translate_x:.12f}" android:translateY="{translate_y:.12f}">
        <path android:fillColor="@android:color/transparent"
            android:strokeColor="{FOREGROUND}" android:strokeWidth="38"
            android:strokeLineCap="round"
            android:pathData="{path}" />
    </group>
</vector>
''')

write("app/src/main/res/values/colors.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate_icon.py. -->
<resources>
    <color name="ic_launcher_background">{BACKGROUND}</color>
</resources>
''')

write("assets/icon.svg", f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">
  <!-- Generated by scripts/generate_icon.py. -->
  <circle cx="54" cy="54" r="36" fill="{BACKGROUND}"/>
  <g transform="translate({translate_x:.12f} {translate_y:.12f}) scale({scale:.12f} {-scale:.12f})"
      fill="none" stroke="{FOREGROUND}" stroke-width="38" stroke-linecap="round">
    <path d="{path}"/>
  </g>
</svg>
''')
